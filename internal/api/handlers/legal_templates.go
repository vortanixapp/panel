func legalTemplate(kind string, p accountingProfile, now time.Time) (string, string) {
	seller := firstNonEmpty(p.FullName, p.Name, p.AppName)
	ogrn := ""
	if p.OGRN != "" {
		ogrn = " (" + ogrnLabel(p.OGRN) + " " + p.OGRN + ")"
	}
	vat := "без НДС"
	if rate := p.vatRate(); rate != "none" {
		vat = "с учётом НДС " + rate + "%"
	}
	requisites := []string{"- " + seller}
	for _, item := range []struct{ label, value string }{
		{"ИНН", p.INN},
		{"КПП", p.KPP},
		{ogrnLabel(p.OGRN), p.OGRN},
		{"Адрес", p.Address},
		{"Расчётный счёт", p.BankAccount},
		{"Банк", p.BankName},
		{"БИК", p.BankBIK},
		{"Корреспондентский счёт", p.BankCorrAccount},
		{"Электронная почта", p.Email},
		{"Телефон", p.Phone},
	} {
		if item.value != "" {
			requisites = append(requisites, "- "+item.label+": "+item.value)
		}
	}
	replacer := strings.NewReplacer(
		"{seller}", seller,
		"{ogrn}", ogrn,
		"{inn}", firstNonEmpty(p.INN, "—"),
		"{address}", firstNonEmpty(p.Address, "указан в реквизитах на сайте"),
		"{email}", firstNonEmpty(p.Email, "адрес электронной почты, указанный на сайте"),
		"{site}", firstNonEmpty(p.Site, "сайт панели управления"),
		"{date}", russianDate(now),
		"{vat}", vat,
		"{requisites}", strings.Join(requisites, "\n"),
	)
	return legalTitles[kind], replacer.Replace(legalTemplates[kind])
}
