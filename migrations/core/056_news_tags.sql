-- Рубрика, закрепление и отметка о прочтении для новостей.
--
-- Лента была плоским списком карточек: ни разделить обновления и техработы, ни
-- вынести важное наверх, ни понять, что уже читал. Всё это лента показывает по
-- макету, и хранить его в meta нельзя — по рубрике идёт фильтр со счётчиками,
-- а фильтровать по полю JSONB без индекса значит перебирать таблицу целиком.
ALTER TABLE core.news
    ADD COLUMN IF NOT EXISTS tag TEXT NOT NULL DEFAULT 'update',
    ADD COLUMN IF NOT EXISTS pinned BOOLEAN NOT NULL DEFAULT false;

-- Без CHECK: набор рубрик задаёт владелец панели, и список значений в схеме
-- запрещал бы ему завести свою — ровно та же история, что с отделами
-- поддержки, где ограничение пришлось бы снимать миграцией.
CREATE INDEX IF NOT EXISTS idx_news_tag
    ON core.news (tenant_id, tag, published_at DESC);

-- Закреплённая новость выбирается отдельным запросом, поэтому индекс частичный:
-- закреплена обычно одна из сотен.
CREATE INDEX IF NOT EXISTS idx_news_pinned
    ON core.news (tenant_id, published_at DESC) WHERE pinned;

-- Прочитанное отмечаем одной датой на пользователя, а не строкой на каждую
-- пару «пользователь-новость».
--
-- Лента показывает только «новое с прошлого захода», и для этого достаточно
-- сравнить дату публикации с этой отметкой. Таблица связей дала бы то же самое,
-- но росла бы как число пользователей на число новостей и требовала бы уборки
-- при удалении и того и другого.
--
-- NULL означает «не читал ничего»: у существующих пользователей все новости
-- окажутся новыми, и это честнее, чем молча пометить прочитанным то, чего они
-- не видели.
ALTER TABLE core.users
    ADD COLUMN IF NOT EXISTS news_read_at TIMESTAMPTZ;
