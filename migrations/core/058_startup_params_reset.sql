-- Сброс параметров запуска перед тем, как они начнут работать.
--
-- Поле «Параметры запуска» много месяцев ничего не делало: все образы читают
-- строку из /data/.vtx/startup_params, но записывать её было некому — при
-- переезде с legacy-демона на Go пишущая сторона потерялась, читающая осталась.
-- Теперь агент этот файл пишет, и всё, что накопилось в базе, разом стало бы
-- действующим при первом же перезапуске.
--
-- Включать это вслепую нельзя по двум причинам.
--
-- Первая: строка, начинающаяся с `/` или `./`, по логике entrypoint заменяет
-- команду запуска целиком, а не дописывается к ней. Достаточно одной такой
-- записи, чтобы сервер перестал подниматься.
--
-- Вторая: значение накапливалось в двух несовместимых формах. Ручка
-- ServerStartupParams писала в это поле всё тело запроса, то есть объект
-- {"startup_params": "..."}, а форма настроек — обычную строку. Разбирать эту
-- смесь ради данных, которые ни разу не применялись, смысла нет.
--
-- Отдельно про Valheim и стартовую карту CS 1.6: у них это поле было
-- единственным местом хранения настроек, и заманчиво перенести значения в
-- game_settings, чтобы не пропали. Делать этого как раз нельзя. Сервер сейчас
-- работает на значениях по умолчанию из entrypoint, а не на том, что показывает
-- панель. Перенос заставил бы Valheim при следующем старте открыть мир с другим
-- именем — то есть создать пустой рядом с настоящим, и клиент решил бы, что
-- потерял сохранение. Очистка оставляет поведение ровно таким, какое оно
-- сегодня, а настройки клиент задаст осознанно и увидит результат.
UPDATE core.servers
SET config = config - 'startup_params'
WHERE config ? 'startup_params';
